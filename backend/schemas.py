"""Pydantic schemas: the API contract and the mission structure the AI must produce."""

from __future__ import annotations

from enum import Enum
from typing import List, Literal, Optional

from pydantic import BaseModel, Field, field_validator

from .config import VALID_DURATIONS


class ActivityType(str, Enum):
    explore_nature = "explore_nature"
    move = "move"
    clear_my_head = "clear_my_head"
    observe = "observe"


class EnergyLevel(str, Enum):
    low = "low"
    moderate = "moderate"
    high = "high"


class Difficulty(str, Enum):
    chill = "chill"
    steady = "steady"
    push = "push"


class CompletionMode(str, Enum):
    manual = "manual"
    timer = "timer"


class TaskStatus(str, Enum):
    pending = "pending"
    in_progress = "in_progress"
    completed = "completed"
    skipped = "skipped"


class MissionRequest(BaseModel):
    """What the user picks on the setup screen."""

    activity: ActivityType
    duration_minutes: Literal[15, 30, 60]
    energy: EnergyLevel = EnergyLevel.moderate
    difficulty: Difficulty = Difficulty.steady
    context: str = Field(default="", max_length=400)

    @field_validator("context")
    @classmethod
    def strip_context(cls, value: str) -> str:
        return value.strip()


class MissionTask(BaseModel):
    """One step of a mission. IDs are assigned by the backend, never by the model."""

    id: str = ""
    instruction: str = Field(min_length=10, max_length=280)
    target_minutes: int = Field(ge=1, le=45)
    completion_mode: CompletionMode = CompletionMode.manual


class Mission(BaseModel):
    """A validated, ready-to-run outdoor mission."""

    title: str = Field(min_length=3, max_length=80)
    description: str = Field(min_length=10, max_length=500)
    total_duration_minutes: int
    tasks: List[MissionTask] = Field(min_length=3, max_length=5)
    completion_mode: CompletionMode = CompletionMode.manual
    safety_notes: List[str] = Field(min_length=1, max_length=6)
    activity: Optional[ActivityType] = None
    energy: Optional[EnergyLevel] = None
    difficulty: Optional[Difficulty] = None
    # "ai" = generated by the configured model. "sample" = bundled demo mission,
    # which the UI always labels as NOT AI-generated.
    source: Literal["ai", "sample"] = "ai"
    provider: Optional[str] = None
    model: Optional[str] = None
    generated_at: Optional[str] = None
    warnings: List[str] = Field(default_factory=list)

    @field_validator("total_duration_minutes")
    @classmethod
    def duration_is_allowed(cls, value: int) -> int:
        if value not in VALID_DURATIONS:
            raise ValueError(f"total_duration_minutes must be one of {VALID_DURATIONS}")
        return value


class GenerateMissionResponse(BaseModel):
    mission: Mission


class ValidationIssue(BaseModel):
    field: str
    message: str


class HealthResponse(BaseModel):
    status: str = "ok"
    provider: str
    model: str


class ConfigResponse(BaseModel):
    provider: str
    provider_label: str
    model: str
    sample_available: bool
