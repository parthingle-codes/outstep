import { CheckIcon, ClockIcon } from './Icons.jsx'
import { activityLabel } from '../constants.js'

export function SourceBadge({ mission }) {
  if (mission.source === 'sample') {
    return (
      <span className="badge badge--sample" title="Bundled demo mission — not generated by AI">
        Sample mission · not AI-generated
      </span>
    )
  }
  return (
    <span className="badge badge--ai" title="Generated by your configured model">
      AI · {mission.provider}
      {mission.model ? ` · ${mission.model}` : ''}
    </span>
  )
}

export function SafetyNotes({ notes }) {
  if (!notes?.length) return null
  return (
    <details className="safety">
      <summary>Safety notes</summary>
      <ul className="safety__list">
        {notes.map((note, index) => (
          <li key={index}>{note}</li>
        ))}
      </ul>
    </details>
  )
}

export default function MissionCard({ mission, children }) {
  const taskTotal = mission.tasks.reduce((sum, task) => sum + task.target_minutes, 0)

  return (
    <article className="mission-card">
      <header className="mission-card__header">
        <SourceBadge mission={mission} />
        <h1 className="mission-card__title">{mission.title}</h1>
        <p className="mission-card__description">{mission.description}</p>
        <div className="mission-card__meta">
          <span className="pill">{mission.total_duration_minutes} min planned</span>
          <span className="pill">{mission.tasks.length} tasks</span>
          <span className="pill">~{taskTotal} min of tasks</span>
          <span className="pill">{activityLabel(mission.activity)}</span>
        </div>
        {mission.generated_at && (
          <p className="mission-card__stamp">
            Generated {new Date(mission.generated_at).toLocaleString()}
          </p>
        )}
        {mission.warnings?.length > 0 && (
          <p className="mission-card__warnings">
            Adjusted after validation: {mission.warnings.join('; ')}
          </p>
        )}
      </header>

      <ol className="task-list">
        {mission.tasks.map((task, index) => (
          <li key={task.id || index} className="task-card">
            <div className="task-card__index" aria-hidden="true">
              {index + 1}
            </div>
            <div className="task-card__body">
              <p className="task-card__instruction">{task.instruction}</p>
              <div className="task-card__meta">
                <span className="chip">
                  <ClockIcon size={14} /> {task.target_minutes} min
                </span>
                <span className="chip chip--mode">
                  {task.completion_mode === 'timer' ? 'Timer' : 'Tap when done'}
                </span>
              </div>
            </div>
          </li>
        ))}
      </ol>

      <SafetyNotes notes={mission.safety_notes} />

      {children && <div className="mission-card__actions">{children}</div>}
    </article>
  )
}

export function TaskStatusIcon({ status }) {
  if (status === 'completed') {
    return (
      <span className="status-dot status-dot--done">
        <CheckIcon size={14} />
      </span>
    )
  }
  if (status === 'skipped') {
    return <span className="status-dot status-dot--skipped">–</span>
  }
  if (status === 'in_progress') {
    return <span className="status-dot status-dot--running" />
  }
  return <span className="status-dot status-dot--pending" />
}
